fn cedar_rows(forward: &law1::PropellerMap) -> [Vec<PropellerCellDefinition>; 2] {
    NEGATIVE_ADVANCE_RATIO_KNOTS.map(|j| {
        forward
            .definition()
            .blade_pitch_rad
            .iter()
            .map(|&beta| {
                let ct = 0.5 * (beta - (j / (0.75 * PI)).atan());
                // Original continuation reference, not an adverse-flow theorem.
                let reference = ct / 2.0 * (j + (j * j + 8.0 * ct / PI).sqrt());
                PropellerCellDefinition {
                    ct,
                    cp: 1.22 * reference + 0.005 + 0.01 * beta,
                }
            })
            .collect()
    })
}
fn cedar() -> TurbopropAircraftConfig {
    let forward = cedar_forward();
    let rows = cedar_rows(forward.propeller());
    TurbopropAircraftConfig::from_forward(forward, rows).unwrap()
}
