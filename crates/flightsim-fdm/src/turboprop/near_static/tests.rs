#[test]
fn cedar_exact_law1_boundary_remains_rejected_and_law2_executes_same_input() {
    let state = boundary_state();
    let controls = ControlInputs::neutral().with_brakes(1.0);
    let environment = Environment::still_air();
    let dt = Seconds(1.0 / 120.0);
    let mut old = law1::TurbopropFlightDynamics::new(cedar_forward(), state).unwrap();
    let error = old.step(dt, controls, &environment).unwrap_err();
    assert_eq!(error.stage, TurbopropStage::K2);
    assert_eq!(error.substep, 2);
    assert!(
        matches!(error.reason, law1::TurbopropFailureReason::OutsidePropellerDomain(d)
        if d.advance_ratio == AxisStatus::Below && d.blade_pitch == AxisStatus::Within)
    );
    assert_eq!(
        error
            .diagnostics
            .values()
            .advance_ratio
            .unwrap()
            .0
            .to_bits(),
        (-4.878_198_680_520_810_5e-6_f64).to_bits()
    );
    assert_eq!(state_bits(old.state()), state_bits(&state));
    let mut new = TurbopropFlightDynamics::new(cedar(), state).unwrap();
    let report = new.step(dt, controls, &environment).unwrap();
    assert!(report.substeps >= 3 && report.substeps <= MAX_TURBOPROP_SUBSTEPS);
    assert_ne!(state_bits(new.state()), state_bits(&state));
    assert!(new.state().rigid_body.is_finite());
}

#[test]
fn forward_queries_and_steps_remain_bit_exact() {
    let config = cedar();
    let map = config.propeller();
    for j in [-0.0, 0.0, 0.025, 0.25, 0.95, 1.4] {
        for beta in [0.07, 0.083, 0.24, 0.719, 0.72] {
            let q = query(j, beta);
            assert_eq!(
                map.sample(q, KilogramsPerCubicMeter(1.225), RadiansPerSecond(180.0)),
                map.forward_map()
                    .sample(q, KilogramsPerCubicMeter(1.225), RadiansPerSecond(180.0))
                    .map_err(Into::into)
            );
        }
    }
    let mut start = level(1000.0, 40.0);
    start.blade_pitch_rad = Radians(0.35);
    let mut old =
        law1::TurbopropFlightDynamics::new(config.forward_config().clone(), start).unwrap();
    let mut new = TurbopropFlightDynamics::new(config, start).unwrap();
    let controls = ControlInputs::neutral().with_throttle(0.4);
    for _ in 0..120 {
        assert_eq!(
            old.step(Seconds(1.0 / 120.0), controls, &Environment::still_air())
                .unwrap(),
            new.step(Seconds(1.0 / 120.0), controls, &Environment::still_air())
                .unwrap()
        );
        assert_eq!(state_bits(old.state()), state_bits(new.state()));
    }
}

#[test]
fn explicit_negative_rows_and_zero_are_continuous_with_static_power_margin() {
    let config = cedar();
    let map = config.propeller();
    for (r, &j) in NEGATIVE_ADVANCE_RATIO_KNOTS.iter().enumerate() {
        for (p, &beta) in map
            .forward_map()
            .definition()
            .blade_pitch_rad
            .iter()
            .enumerate()
        {
            let c = map.coefficients(query(j, beta)).unwrap();
            assert_eq!(c.ct.to_bits(), map.negative_rows()[r][p].ct.to_bits());
            assert_eq!(c.cp.to_bits(), map.negative_rows()[r][p].cp.to_bits());
        }
    }
    let pitches = &map.forward_map().definition().blade_pitch_rad;
    let mut smallest_margin = f64::INFINITY;
    for (r, &j0) in NEGATIVE_ADVANCE_RATIO_KNOTS.iter().enumerate() {
        let j1 = if r == 0 {
            NEGATIVE_ADVANCE_RATIO_KNOTS[1]
        } else {
            0.0
        };
        for p in pitches.windows(2) {
            for a in 0..=16 {
                for b in 0..=16 {
                    let j = j0 + (j1 - j0) * f64::from(a) / 16.0;
                    let beta = p[0] + (p[1] - p[0]) * f64::from(b) / 16.0;
                    let c = map.coefficients(query(j, beta)).unwrap();
                    let floor = (2.0 / PI).sqrt() * c.ct.powf(1.5);
                    smallest_margin = smallest_margin.min(c.cp - floor);
                    assert!(c.ct > 0.0 && c.cp > 0.0 && c.cp >= floor);
                }
            }
        }
    }
    close(smallest_margin, 0.006_732_719_705_404_812_5, 1e-15);
    for beta in [0.07, 0.24, 0.719, 0.72] {
        let zero = map
            .sample(
                query(0.0, beta),
                KilogramsPerCubicMeter(1.0),
                RadiansPerSecond(180.0),
            )
            .unwrap();
        for j in [-1e-12, -f64::from_bits(1), -0.0, f64::from_bits(1), 1e-12] {
            let adjacent = map
                .sample(
                    query(j, beta),
                    KilogramsPerCubicMeter(1.0),
                    RadiansPerSecond(180.0),
                )
                .unwrap();
            close(adjacent.thrust.get(), zero.thrust.get(), 1e-6);
            close(
                adjacent.absorbed_power.get(),
                zero.absorbed_power.get(),
                1e-4,
            );
            close(adjacent.load_torque.get(), zero.load_torque.get(), 1e-6);
        }
    }
}

#[test]
fn static_floor_rejects_continuation_only_power_nonpositive_and_underflow() {
    let forward = cedar_forward();
    for (ct, cp) in [
        (0.1, 0.025),
        (0.1, 0.0),
        (0.1, -0.0),
        (0.0, 0.08),
        (-0.01, 0.08),
        (f64::from_bits(1), 0.08),
        (f64::NAN, 0.08),
        (0.1, f64::INFINITY),
    ] {
        let mut rows = cedar_rows(forward.propeller());
        rows[0][0] = PropellerCellDefinition { ct, cp };
        assert!(
            PropellerMap::from_forward(forward.propeller().clone(), rows).is_err(),
            "{ct} {cp}"
        );
    }
    let mut rows = cedar_rows(forward.propeller());
    rows[1].pop();
    assert!(PropellerMap::from_forward(forward.propeller().clone(), rows).is_err());
    let mut rows = cedar_rows(forward.propeller());
    rows[0][0].cp = 1.0;
    assert!(PropellerMap::from_forward(forward.propeller().clone(), rows).is_err());
    // A negative/nonpositive static endpoint was legal to law1, but cannot
    // furnish the new branch's continuous positive-thrust closure.
    let mut d = propeller_definition();
    d.cells[0].ct = 0.0;
    let old = law1::PropellerMap::from_definition(d).unwrap();
    let row = vec![PropellerCellDefinition { ct: 0.01, cp: 0.03 }; 2];
    assert!(PropellerMap::from_forward(old, [row.clone(), row]).is_err());
}

