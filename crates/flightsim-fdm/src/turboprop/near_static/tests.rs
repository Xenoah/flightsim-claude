#[test]
fn hover_scale_ratio_bounds_include_exact_endpoints_and_reject_adjacent_outside() {
    let check = |axial, transverse| {
        propeller::flow_scale(
            Newtons(200.0 * PI),
            KilogramsPerCubicMeter(1.0),
            Meters(2.0),
            MetersPerSecond(axial),
            MetersPerSecond(transverse),
        )
        .unwrap()
    };
    let exact = check(-1.0, 1.0);
    assert_eq!(exact.hover_velocity.get().to_bits(), 10.0_f64.to_bits());
    assert_eq!(exact.adverse_ratio.to_bits(), 0.1_f64.to_bits());
    assert_eq!(exact.transverse_ratio.to_bits(), 0.1_f64.to_bits());
    assert!(exact.domain().is_supported());
    assert!(
        check((-1.0_f64).next_up(), (1.0_f64).next_down())
            .domain()
            .is_supported()
    );
    assert_eq!(
        check((-1.0_f64).next_down(), 1.0).domain().adverse_inflow,
        AxisStatus::Above
    );
    assert_eq!(
        check(-1.0, (1.0_f64).next_up()).domain().transverse_inflow,
        AxisStatus::Above
    );
    for thrust in [0.0, -1.0, f64::from_bits(1), f64::MAX, f64::NAN] {
        let density = if thrust.to_bits() == f64::MAX.to_bits() {
            f64::from_bits(1)
        } else {
            1.0
        };
        assert!(
            propeller::flow_scale(
                Newtons(thrust),
                KilogramsPerCubicMeter(density),
                Meters(2.0),
                MetersPerSecond(-1.0),
                MetersPerSecond(0.0)
            )
            .is_none()
        );
    }
}

#[test]
fn negative_flow_checks_add_to_existing_limits_and_keep_full_state_atomic() {
    let mut state = level(1000.0, 0.0);
    state.rigid_body.velocity = state.rigid_body.orientation * DVec3::new(-0.1, 1.0, 0.0);
    let mut model = TurbopropFlightDynamics::new(config(), state).unwrap();
    let e = model
        .step(
            Seconds::ZERO,
            ControlInputs::neutral(),
            &Environment::still_air(),
        )
        .unwrap_err();
    assert!(
        matches!(e.reason, TurbopropFailureReason::OutsideNearStaticDomain(d) if d.transverse_inflow == AxisStatus::Above)
    );
    assert!(e.diagnostics.values().transverse_inflow_ratio.unwrap() > 0.1);
    assert_eq!(state_bits(model.state()), state_bits(&state));

    // This fixture's smaller CT reaches the adverse ratio before J=-0.01.
    state.rigid_body.velocity = state.rigid_body.orientation * DVec3::new(-0.5, 0.0, 0.0);
    model.set_state(state).unwrap();
    let e = model
        .step(
            Seconds::ZERO,
            ControlInputs::neutral(),
            &Environment::still_air(),
        )
        .unwrap_err();
    assert!(
        matches!(e.reason, TurbopropFailureReason::OutsideNearStaticDomain(d) if d.adverse_inflow == AxisStatus::Above)
    );
    assert!(e.diagnostics.values().advance_ratio.unwrap().0 > -0.01);
    assert_eq!(state_bits(model.state()), state_bits(&state));
    // At positive flow the same transverse velocity retains law1's behavior.
    state.rigid_body.velocity = state.rigid_body.orientation * DVec3::new(0.1, 1.0, 0.0);
    model.set_state(state).unwrap();
    model
        .step(
            Seconds::ZERO,
            ControlInputs::neutral(),
            &Environment::still_air(),
        )
        .unwrap();
    // Existing tangential crossflow and tip limits still precede the new guard.
    state.rigid_body.velocity = state.rigid_body.orientation * DVec3::new(-0.1, 30.0, 0.0);
    model.set_state(state).unwrap();
    assert!(
        matches!(model.step(Seconds::ZERO, ControlInputs::neutral(), &Environment::still_air()).unwrap_err().reason,
        TurbopropFailureReason::OutsideOperatingEnvelope(d) if d.crossflow == AxisStatus::Above)
    );
    assert_eq!(state_bits(model.state()), state_bits(&state));
}

