// Fixture-only adapter, not a production profile reader. Raw tokens first go
// through Rust's correctly rounded parser, then Value stores those exact bits.
// Ordinary serde_json f64 token conversion is never used for physical values.
fn exact_fixture_value(raw: &RawValue) -> Value {
    let token = raw.get();
    match token.as_bytes()[0] {
        b'{' => {
            let fields: BTreeMap<String, &RawValue> = serde_json::from_str(token).unwrap();
            Value::Object(
                fields
                    .into_iter()
                    .map(|(key, value)| (key, exact_fixture_value(value)))
                    .collect(),
            )
        }
        b'[' => {
            let values: Vec<&RawValue> = serde_json::from_str(token).unwrap();
            Value::Array(values.into_iter().map(exact_fixture_value).collect())
        }
        b'"' | b'n' | b't' | b'f' => serde_json::from_str(token).unwrap(),
        _ if token.contains(['.', 'e', 'E']) || token == "-0" => {
            Value::Number(serde_json::Number::from_f64(token.parse::<f64>().unwrap()).unwrap())
        }
        // Preserve integer schema/sense tags; all fixture integers fit binary64.
        _ => serde_json::from_str(token).unwrap(),
    }
}
fn cedar_forward() -> law1::TurbopropAircraftConfig {
    let raw: &RawValue = serde_json::from_str(include_str!(
        "../../../tests/fixtures/cedar-law1-components.json"
    ))
    .unwrap();
    let d: CedarComponents = serde_json::from_value(exact_fixture_value(raw)).unwrap();
    law1::TurbopropAircraftConfig::new(
        d.airframe.to_config().unwrap(),
        TurbinePowerTable::from_definition(d.turbine).unwrap(),
        law1::PropellerMap::from_definition(d.propeller).unwrap(),
        SampledGovernor::from_definition(d.governor).unwrap(),
        MachAeroSchedule::from_definition(d.aero).unwrap(),
        TurbopropEnvelope::from_definition(d.envelope).unwrap(),
    )
    .unwrap()
}

fn numeric_inventory(value: &Value, path: &str, output: &mut BTreeMap<String, String>) {
    match value {
        Value::Number(n) => {
            output.insert(
                path.to_owned(),
                format!("{:016x}", n.as_f64().unwrap().to_bits()),
            );
        }
        Value::Array(values) => {
            for (i, value) in values.iter().enumerate() {
                numeric_inventory(value, &format!("{path}/{i}"), output);
            }
        }
        Value::Object(fields) => {
            for (key, value) in fields {
                numeric_inventory(value, &format!("{path}/{key}"), output);
            }
        }
        _ => {}
    }
}

