#[test]
fn adverse_branch_stage_and_later_substep_guard_failures_roll_back_every_bit() {
    // Horizontal flight axes and downward velocity: gravity carries the
    // transverse flow through the fixed limit. There is no controller or
    // artificial force, velocity clamp, lowered bound or altered gear here.
    for (downward, dt, stage, substep) in [
        (0.5, 1.0 / 120.0, TurbopropStage::Initial, 0),
        (0.42, 1.0 / 120.0, TurbopropStage::K2, 0),
        (0.40, 1.0 / 120.0, TurbopropStage::K4, 0),
        (0.32, 1.0 / 60.0, TurbopropStage::K4, 1),
    ] {
        let mut start = level(1000.0, 0.0);
        start.rigid_body.velocity = start.rigid_body.orientation * DVec3::new(-0.1, 0.0, downward);
        let mut model = TurbopropFlightDynamics::new(config(), start).unwrap();
        let e = model
            .step(
                Seconds(dt),
                ControlInputs::neutral(),
                &Environment::still_air(),
            )
            .unwrap_err();
        assert_eq!(e.stage, stage);
        assert_eq!(e.substep, substep);
        assert!(
            matches!(e.reason, TurbopropFailureReason::OutsideNearStaticDomain(d) if d.transverse_inflow == AxisStatus::Above)
        );
        assert!(e.diagnostics.values().advance_ratio.unwrap().0 < 0.0);
        assert_eq!(state_bits(model.state()), state_bits(&start));
    }
}

#[test]
fn negative_flow_preserves_both_rotation_senses_torque_energy_and_signed_work() {
    for sense in [-1, 1] {
        let mut r = propeller_definition();
        r.rotation_sense = sense;
        let cfg = config_from(
            airframe_definition(),
            power_definition(),
            r,
            governor_definition(),
            envelope_definition(),
        )
        .unwrap();
        let mut state = level(1000.0, 0.0);
        state.rigid_body.velocity = state.rigid_body.orientation * DVec3::new(-0.1, 0.0, 0.0);
        state.rigid_body.angular_velocity = DVec3::new(0.3, -0.2, 0.1);
        let b = state.rigid_body.angular_velocity;
        let w = state.shaft_rad_s.get();
        let s = f64::from(sense);
        let absolute = w + s * b.x;
        let rho = crate::Atmosphere::standard()
            .sample(state.rigid_body.position.to_geodetic().altitude)
            .density
            .get();
        let n = absolute / (2.0 * PI);
        let cp = 0.12;
        let qp = cp * rho * n.powi(3) * 32.0 / absolute;
        let qd = (30_000.0 + 220_000.0 * 0.4) / w;
        let model = TurbopropFlightDynamics::new(cfg.clone(), state).unwrap();
        let d = model
            .derivative(&state, ControlInputs::neutral(), &Environment::still_air())
            .unwrap();
        let alpha = d.rigid_body.angular_acceleration;
        let wd = d.shaft_acceleration.get();
        let inertia = cfg.airframe().mass_properties().inertia();
        let rotor = 20.0;
        let energy_dot =
            b.dot(inertia * alpha) + s * rotor * (wd * b.x + w * alpha.x) + rotor * w * wd;
        close(energy_dot, qd * w - qp * absolute, 2e-9);
        let momentum = inertia * b + DVec3::X * (s * rotor * w);
        let momentum_dot_inertial =
            inertia * alpha + DVec3::X * (s * rotor * wd) + b.cross(momentum);
        close(
            (momentum_dot_inertial + DVec3::X * (s * qp)).length(),
            0.0,
            1e-10,
        );
        let loads = cfg
            .propeller()
            .sample(
                query(-0.1 / (n * 2.0), 0.3),
                KilogramsPerCubicMeter(rho),
                RadiansPerSecond(absolute),
            )
            .unwrap();
        close(
            loads.absorbed_power.get(),
            loads.load_torque.get() * absolute,
            1e-9,
        );
        assert!(loads.thrust.get() * -0.1 < 0.0);
    }
}
